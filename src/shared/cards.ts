const MINORS: TarotCard[] = SUIT_ORDER.flatMap((suit) => {
  const info = SUIT_INFO[suit];
  return MINOR_SOURCE[suit].map(([symbols, upright, reversed, art, guidance], index) => {
    const rank = RANKS[index];
    if (!rank) throw new Error(`${suit} 카드 수가 14장을 넘습니다.`);
    const number = index + 1;
    const card: TarotCard = {
      id: `${suit}-${String(number).padStart(2, '0')}`,
      arcana: 'minor',
      suit,
      number,
      rank: rank.rank,
      nameKo: `${info.nameKo} ${rank.ko}`,
      nameEn: `${rank.en} of ${info.nameEn}`,
      label: rank.label,
      symbols,
      upright,
      reversed,
      art,
    };
    if (guidance) card.guidance = guidance;
    return card;
  });
});

export const CARDS: readonly TarotCard[] = [...MAJORS, ...MINORS];

export const CARD_BY_ID: ReadonlyMap<string, TarotCard> = new Map(CARDS.map((c) => [c.id, c]));

export function getCard(id: string): TarotCard | undefined {
  return CARD_BY_ID.get(id);
}

export function cardImagePath(id: string): string {
  return `assets/cards/${id}.webp`;
}

export const CARD_BACK_PATH = 'assets/cards/card-back.webp';

/** 정·역방향 표기 */
export function orientationLabel(reversed: boolean): string {
  return reversed ? '역방향' : '정방향';
}
